// Copies V4 ABIs from the Foundry build into the indexer as typed `as const` modules.
// Usage: (cd smart-contracts/v4 && forge build) && node scripts/sync-abis.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = ["CircleEngineV4", "AuctionEngineV4", "VaultV4", "MemberRegistryV4"];
const outDir = join(root, "indexer", "abis");
mkdirSync(outDir, { recursive: true });

for (const name of contracts) {
  const { abi } = JSON.parse(readFileSync(join(root, "smart-contracts/v4/out", `${name}.sol`, `${name}.json`), "utf8"));
  const file = join(outDir, `${name}.ts`);
  writeFileSync(file, `// Generated by scripts/sync-abis.mjs — do not edit.\nexport const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`);
  console.log(`wrote ${file}`);
}
